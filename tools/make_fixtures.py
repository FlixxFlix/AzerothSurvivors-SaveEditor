#!/usr/bin/env python3
"""Regenerate the sealed example and the cross-implementation test vectors.

Writes:
    examples/example-save.txt  sealed form of examples/example-save.plain.txt
    src/example.js             the same export as a browser global (works from file://)
    tests/vectors.json         known-answer vectors produced by the Python implementation

All nonces are fixed, so the output is deterministic. Run from the repository root:
    python tools/make_fixtures.py
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rse1  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def nonce(label: str) -> bytes:
    return hashlib.sha256(label.encode()).digest()[:16]


def main() -> None:
    with open(os.path.join(ROOT, "examples/example-save.plain.txt"), encoding="utf-8", newline="") as f:
        example_plain = f.read()
    example = rse1.seal(example_plain, nonce("example-save"))
    with open(os.path.join(ROOT, "examples/example-save.txt"), "w", encoding="utf-8", newline="") as f:
        f.write(example + "\n")
    with open(os.path.join(ROOT, "src/example.js"), "w", encoding="utf-8", newline="") as f:
        f.write("/* Generated by tools/make_fixtures.py from examples/example-save.plain.txt. Invented hero, not a real player's save. */\n")
        f.write(f'window.EXAMPLE_SAVE = "{example}";\n')

    cases = [
        ("one byte", "x"),
        ("exactly one keystream block", "marks|1|1255\nstat|"),
        ("two blocks plus a tail", "equip|1|0:101020,2:101120,4:101220\n"),
        ("non-ASCII text", "enemy.902|Murciélago buscasangre · Taumaturgo sombrío\n"),
        ("example save", example_plain),
    ]
    vectors = []
    for i, (name, plain) in enumerate(cases):
        n = nonce(f"vector-{i}")
        vectors.append({"name": name, "nonce": n.hex(), "plain": plain, "export": rse1.seal(plain, n)})
    with open(os.path.join(ROOT, "tests/vectors.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"generator": "tools/rse1.py (hashlib/hmac)", "vectors": vectors}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"wrote example ({len(example)} chars) and {len(vectors)} vectors")


if __name__ == "__main__":
    main()
